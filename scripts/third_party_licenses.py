"""Write THIRD_PARTY_LICENSES.txt: the license texts of everything the installer ships (#221).

MIT/BSD/Apache require their notice to travel with binary copies, so the installer
bundles this file (src-tauri/tauri.conf.json bundle.resources). CI regenerates it
before each installer build; run it from the repo root with the build venv active:

    python scripts/third_party_licenses.py

Sources: the sidecar's Python runtime closure (installed dist-info), the Tauri shell's
crates (`cargo metadata`, Windows target), the frontend's production npm deps, and
CPython itself.
"""
from __future__ import annotations

import importlib.metadata as md
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_LICENSES.txt"
# The sidecar's runtime roots: pyproject dependencies + the `voice` extra.
PY_ROOTS = ["numpy", "anthropic", "keyring", "fastapi", "uvicorn", "websockets",
            "faster-whisper", "kokoro-onnx", "misaki", "onnxruntime", "regex"]
# Never shipped: excluded from the freeze (packaging/simcoach-sidecar.spec) or not installed.
PY_SKIP = {"av", "phonemizer", "espeakng-loader", "spacy", "num2words"}
NPM_DEPS = ["@tauri-apps/api", "@tauri-apps/plugin-dialog", "svelte"]
_LICENSE_NAME = re.compile(r"(LICEN[CS]E|COPYING|NOTICE|ThirdPartyNotices)", re.IGNORECASE)


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _python() -> list[tuple[str, str, list[str]]]:
    seen: dict[str, md.Distribution] = {}

    def walk(name: str) -> None:
        key = _norm(name)
        if key in seen or key in PY_SKIP:
            return
        try:
            dist = md.distribution(key)
        except md.PackageNotFoundError:
            return  # an optional/platform dep that isn't installed isn't shipped
        seen[key] = dist
        for req in dist.requires or []:
            if "extra ==" not in req:
                walk(re.split(r"[ ;<>=!~\[(]", req, maxsplit=1)[0])

    for root in PY_ROOTS:
        walk(root)
    out = []
    for key in sorted(seen):
        dist = seen[key]
        meta = dist.metadata
        lic = meta.get("License-Expression") or (meta.get("License") or "").split("\n")[0]
        texts = [Path(dist.locate_file(f)).read_text(encoding="utf-8", errors="replace")
                 for f in dist.files or [] if _LICENSE_NAME.search(Path(str(f)).name)
                 and not str(f).endswith((".py", ".pyc"))]
        out.append((f"{dist.name} {dist.version}", lic or "see project", texts))
    base = Path(sys.base_prefix) / "LICENSE.txt"
    if base.is_file():
        out.append((f"CPython {sys.version.split()[0]}", "PSF-2.0",
                    [base.read_text(encoding="utf-8", errors="replace")]))
    return out


def _rust() -> list[tuple[str, str, list[str]]]:
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"],
        cwd=ROOT / "src-tauri"))
    ids = {n["id"] for n in meta["resolve"]["nodes"]}
    out = []
    for pkg in sorted(meta["packages"], key=lambda p: p["name"]):
        if pkg["id"] not in ids or pkg["source"] is None:  # our own crate
            continue
        crate_dir = Path(pkg["manifest_path"]).parent
        texts = [p.read_text(encoding="utf-8", errors="replace")
                 for p in sorted(crate_dir.iterdir()) if p.is_file() and _LICENSE_NAME.search(p.name)]
        out.append((f"{pkg['name']} {pkg['version']}", pkg["license"] or "see crate", texts))
    return out


def _npm() -> list[tuple[str, str, list[str]]]:
    out = []
    for name in NPM_DEPS:
        pkg_dir = ROOT / "frontend" / "node_modules" / name
        if not pkg_dir.is_dir():
            raise SystemExit(f"{pkg_dir} missing: run `npm ci` in frontend/ first")
        pkg = json.loads((pkg_dir / "package.json").read_text(encoding="utf-8"))
        texts = [p.read_text(encoding="utf-8", errors="replace")
                 for p in sorted(pkg_dir.iterdir()) if p.is_file() and _LICENSE_NAME.search(p.name)]
        out.append((f"{name} {pkg['version']}", pkg.get("license", "see package"), texts))
    return out


def main() -> None:
    parts = [("Third-party licenses for Nestor's installer. Generated by "
              "scripts/third_party_licenses.py; see THIRD_PARTY_NOTICES.md for an overview.\n")]
    for title, entries in (("Python (sidecar)", _python()), ("Rust (app shell)", _rust()),
                           ("JavaScript (frontend)", _npm())):
        parts.append(f"\n{'#' * 78}\n# {title}\n{'#' * 78}\n")
        for name, lic, texts in entries:
            parts.append(f"\n{'=' * 78}\n{name}  [{lic}]\n{'=' * 78}\n")
            # ponytail: a package that ships no license file gets its SPDX id only;
            # fetch upstream texts if a distributor ever needs those verbatim too.
            parts.append("\n\n".join(t.strip() for t in texts) + "\n" if texts
                         else "(no license file in the package; license as named above)\n")
    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
